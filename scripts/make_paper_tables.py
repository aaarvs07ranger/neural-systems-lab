def tab_houses() -> str:
    import json
    from config import pair_dir
    meta = mt.pair_meta()
    L = [HEADER, r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
         r"Pair & Target & Reachable cells & Clutter kept & Target swapped & "
         r"Max.\ path shift L1 (m) & Max.\ path shift L2/L3 (m) \\", r"\midrule"]
    for pid in sorted(meta, key=lambda p: meta[p]["cells"]):
        m = meta[pid]
        v = json.loads((pair_dir(pid) / "verification.json").read_text())
        lv = v.get("levels", v)

        def shift(level):
            rec = lv.get(level, {}) if isinstance(lv, dict) else {}
            val = rec.get("max_shortest_path_delta")
            return f"{val:.2f}" if isinstance(val, (int, float)) else "--"
        l23 = [shift("L2"), shift("L3")]
        L.append(f"{pid.replace('pair', 'P')} & {m['target']} & {m['cells']} & {m['clutter']} & "
                 f"{'yes' if m['swappable'] else 'no'} & {shift('L1')} & {' / '.join(l23)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


