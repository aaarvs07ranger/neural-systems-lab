# ------------------------------------------------------------- single change
def tab_single() -> str:
    """Drop (points) when ONE factor changes; bold = each agent's largest drop."""
    res = rs.single_change()
    ag = res["agents"]
    cols = [("F_light", "Light"), ("F_sky", "Sky"), ("F_mat", "Walls/floor"),
            ("F_obj", "Objects"), ("F_tgt", "Goal"), ("F_clut", "Clutter")]
    L = [HEADER, r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
         r" & \multicolumn{3}{c}{L1 factors} & \multicolumn{2}{c}{L2 factors} & L3 \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}\cmidrule(l){7-7}",
         "Agent & " + " & ".join(h for _k, h in cols) + r" \\", r"\midrule"]
    for a in ag:
        vals = {k: ag[a][k]["drop_points"][0] for k, _h in cols}
        best = max(vals, key=vals.get)
        cells = [rf"\textbf{{{r0(vals[k])}}}" if k == best else r0(vals[k]) for k, _h in cols]
        L.append(f"{NAME[a]}{dagger(ag[a]['F_mat'])} & " + " & ".join(cells) + r" \\")
    L.append(r"\midrule")
    mo = res["mean_over_agents"]
    L.append(r"Mean & " + " & ".join(ci_pts(mo[k]) for k, _h in cols) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ budgets
def tab_budget() -> str:
    """House-A and L2 success, and the drop at L2 in points, at both budgets."""
    agents = ["ppo", "ppo_aug", "dreamerv3", "tdmpc2"]
    by = {}
    for grid, tag in ((LADDER_150K, "150k"), (LADDER_300K, "300k")):
        res = rs.ladder(grid)["agents"]
        for b in agents:
            by[(b, tag)] = (res[b]["A"]["success"][0], res[b]["L2"]["success"][0],
                            res[b]["L2"]["drop_points"], res[b]["L2"]["runs"])
    L = [HEADER, r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
         r" & \multicolumn{3}{c}{150k steps} & \multicolumn{3}{c}{300k steps} \\",
         r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
         r"Agent & A & L2 & drop (pts) & A & L2 & drop (pts) \\", r"\midrule"]
    for b in agents:
        c = []
        for t_ in ("150k", "300k"):
            a, l2, drop, n = by[(b, t_)]
            mark = rf"$^{{\dagger{n}}}$" if n < 25 else ""
            c += [f"{a:.2f}", f"{l2:.2f}", ci_pts(drop) + mark]
        L.append(f"{NAME[b]} & " + " & ".join(c) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


# --------------------------------------------------------------- ingredients
# (X, Y, group): what changing X into Y buys. Gap = drop(X) - drop(Y), so a
# positive gap means Y drops less.
COMPARISONS = [
    ("ppo", "ppo_aug", "Colour augmentation"),
    ("ppo", "tdmpc2", "A world model, encoder learned from scratch"),
    ("ppo", "dreamerv3", "A world model, encoder learned from scratch"),
    ("ppo", "ppo_jepa", "A frozen pretrained encoder"),
    ("ppo", "ppo_mae", "A frozen pretrained encoder"),
    ("ppo", "ppo_dino", "A frozen pretrained encoder"),
    ("tdmpc2", "tdmpc2_dino", "Both: a world model on the frozen DINOv2 encoder"),
    ("ppo_dino", "tdmpc2_dino", "Both: a world model on the frozen DINOv2 encoder"),
]


def _pair(res: Dict, table: str, x: str, y: str, rung: str):
    """Gap or P for (x, y) whichever order robust_stats stored it in."""
    from config import AGENT_ORDER
    if AGENT_ORDER.index(x) < AGENT_ORDER.index(y):
        return res[table][f"{x}>{y}@{rung}"], False
    return res[table][f"{y}>{x}@{rung}"], True


def tab_compare() -> str:
    """Gap in drop (points, 95% CI) for each ingredient, and P(Y beats X) at L2."""
    res = rs.ladder(LADDER_300K)
    L = [HEADER, r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
         r" & \multicolumn{3}{c}{Reduction in drop (points)} & $P$(Y beats X) \\",
         r"\cmidrule(lr){2-4}\cmidrule(l){5-5}",
         r"From X to Y & L1 & L2 & L3 & at L2 \\", r"\midrule"]
    group = None
    for x, y, g in COMPARISONS:
        if g != group:
            if group is not None:
                L.append(r"\addlinespace[2pt]")
            L.append(rf"\multicolumn{{5}}{{@{{}}l}}{{\textit{{{g}}}}} \\")
            group = g
        cells = []
        for rung in mt.SHIFTED:
            v, flipped = _pair(res, "gap_in_drop", x, y, rung)
            cells.append(ci_pts([-v[0], -v[2], -v[1]] if flipped else v))
        pv, flipped = _pair(res, "prob_improvement", x, y, "L2")
        # stored as P(first beats second); we want P(Y beats X)
        pyx = pv if flipped else [1 - pv[0], 1 - pv[2], 1 - pv[1]]
        cells.append(f"{pyx[0]:.2f} {{\\scriptsize[{pyx[1]:.2f}, {pyx[2]:.2f}]}}")
        L.append(f"\\quad {NAME[x]} $\\to$ {NAME[y]} & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


def tab_rgb() -> str:
    """Within-house rank correlation between colour shift and drop, by kind of change."""
    import json
    res = json.loads((TABLES / "rgb_shift_analysis.json").read_text())

    def cell(key):
        rho, p = (res["within"] if key.count("|") == 1 else res["by_kind"])[key]
        p_txt = "$<$0.001" if p < 0.001 else f"{p:.3f}"
        return f"{signed(rho, '+.2f')} {{\\scriptsize({p_txt})}}"
    L = [HEADER, r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
         r" & \multicolumn{3}{c}{Colour shift (W1)} & \multicolumn{2}{c}{Per-pixel difference} \\",
         r"\cmidrule(lr){2-4}\cmidrule(l){5-6}",
         r"Agent & all changes & no repaint & repaint & all changes & no repaint \\", r"\midrule"]
    for a in res["agents"] + ["all"]:
        name = "Mean over agents" if a == "all" else NAME[a]
        if a == "all":
            L.append(r"\midrule")
        L.append(f"{name} & " + " & ".join([
            cell(f"w1_mean|{a}"), cell(f"no_repaint|w1_mean|{a}"), cell(f"repaint|w1_mean|{a}"),
            cell(f"mean_abs_diff|{a}"), cell(f"no_repaint|mean_abs_diff|{a}")]) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


