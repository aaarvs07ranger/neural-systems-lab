FAM_RE = re.compile(r"^\s*(.+?)\s+vs\s+(.+?)\s+([+-]\d+\.\d)%\s+p=([\d.]+)\s+Holm p=([\d.]+)")


def families(path: Path, which: str) -> Dict[str, List[tuple]]:
    """Parse the declared Holm families from the competency-filtered block."""
    text = path.read_text()
    block = text.split("RUNS WITH HOUSE-A SUCCESS >= 0.5")[1]
    fams: Dict[str, List[tuple]] = {}
    cur = None
    for line in block.splitlines():
        if "FAMILY" in line:
            cur = line.strip().split(" — ")[0]
            fams[cur] = []
        elif cur:
            m = FAM_RE.match(line)
            if m:
                a, b = STATS_NAME[m.group(1).strip()], STATS_NAME[m.group(2).strip()]
                fams[cur].append((a, b, float(m.group(3)), float(m.group(4)), float(m.group(5))))
    return fams


def tab_families() -> str:
    fams = families(TABLES / "grid_stats_300k.md", "300k")
    label = {"ALL-PAIRS FAMILY": "All pairs, success at L2 (28 comparisons)",
             "ORIGINAL-FOUR FAMILY": "Original four agents, success at L2 (6; fixed before any pretrained encoder was run)",
             "DINOv2 FAMILY": "PPO+DINOv2 vs.\\ each agent that existed when fixed, success at L1 (6)",
             "TD-MPC2+DINOv2 FAMILY": "TD-MPC2+DINOv2 vs.\\ each agent, success at L1 (7)"}
    L = [HEADER, r"\begin{tabular}{@{}llccc@{}}", r"\toprule",
         r"Agent 1 & Agent 2 & Gap in relative drop (pts) & $p$ & $p$ (Holm) \\", r"\midrule"]
    for i, (key, rows) in enumerate(fams.items()):
        if i:
            L.append(r"\midrule")
        L.append(rf"\multicolumn{{5}}{{@{{}}l}}{{\textit{{{label.get(key, key)}}}}} \\")
        for a, b, gap, p, ph in rows:
            ph_txt = r"\textbf{" + p_tex(ph) + "}" if ph < 0.05 else p_tex(ph)
            L.append(f"{NAME[a]} & {NAME[b]} & {signed(gap, '+.1f')} & {p_tex(p)} & {ph_txt} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


