"""LaTeX tables for the paper, generated from committed results -- never typed.

Same rule as make_tables.py: a number that is copied by hand can drift from the
data without anyone noticing, so every table the paper prints is written here.
Sources:

  results/ladder_300k/, results/ladder_150k/   per-run ladder summaries
  results/single_change_300k/                  single-change evaluation pass
  results/reordered_ladder_300k/               reordered-ladder evaluation pass
  robust_stats.py                              95% CIs (same functions, same seeds,
                                               so the paper and results/tables agree)
  results/tables/grid_stats_300k.md            declared Holm families (parsed;
                                               re-running 10^5 permutations to
                                               reprint numbers already generated
                                               would add nothing)
  test_target_effect.analyse                   goal-object control

Wording rule (Vishwas, 2026-09-29): success RATES and DROPS in success rate, in
percentage points. Never "loss" or "share of success lost"; a relative drop
appears only in brackets.

    python scripts/make_paper_tables.py        # -> paper_v2/generated/*.tex
"""
